    BINDINGS = [
        ("left", "prev_step", "☁ back"),
        ("right", "next_step", "✧ next"),
        ("space", "next_step", "⋆ space"),
        ("q", "quit", "☁ quit")
    ]

    def __init__(self):
        super().__init__()
        self.flat_steps = []
        
        for row_idx, row in enumerate(TRICOT_INSTRUCTIONS):
            for step_idx, item in enumerate(row):
                if isinstance(item, tuple):
                    main_text = item[0]
                    explanation = item[1]
                else:
                    main_text = item
                    explanation = ""
                
                self.flat_steps.append({
                    "text": main_text.lower(),
                    "explanation": explanation.lower(),
                    "row_num": row_idx + 1,
                    "step_num": step_idx + 1,
                    "total_steps_in_row": len(row)
                })
        
        self.current_index = 0
        self.total_steps = len(self.flat_steps)

    def compose(self) -> ComposeResult:
        yield Header(show_clock=True)
        with Center():
            with Middle(id="container"):
                yield Label("", id="text-display")
                yield Label("", id="explanation-display")
                yield Label("", id="meta-info")
                yield ProgressBar(total=self.total_steps, show_eta=False, show_percentage=False)
        yield Footer()

    def on_mount(self) -> None:
        self.title = "knit flow counter ✧" # dynamically set header title to lowercase style
        self.update_ui()

    def update_ui(self) -> None:
        current_data = self.flat_steps[self.current_index]
        
        self.query_one("#text-display", Label).update(current_data["text"])
        self.query_one("#explanation-display", Label).update(current_data["explanation"])
        
        meta_text = (
            f"row {current_data['row_num']} ✧ step {current_data['step_num']}/{current_data['total_steps_in_row']} "
            f"⋆ global: {self.current_index + 1}/{self.total_steps}"
        )
        self.query_one("#meta-info", Label).update(meta_text)
        
        self.query_one(ProgressBar).progress = self.current_index + 1

    def action_next_step(self) -> None:
        if self.current_index < self.total_steps - 1:
            self.current_index += 1
            self.update_ui()

    def action_prev_step(self) -> None:
        if self.current_index > 0:
            self.current_index -= 1
            self.update_ui()


